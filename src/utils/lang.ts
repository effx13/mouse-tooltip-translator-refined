// Uses Intl.DisplayNames (CLDR data built into the browser) with the extension
// UI language; falls back to the curated English name when the tag is invalid
// or CLDR has no data (rare google-only codes like "alz").
// English UI keeps the curated names as-is.
const displayNamesCache = new Map<string, Intl.DisplayNames | null>();
function getDisplayNames(uiLang: string) {
  if (!displayNamesCache.has(uiLang)) {
    let names: Intl.DisplayNames | null = null;
    try {
      names = new Intl.DisplayNames([uiLang], { type: "language", fallback: "none" });
    } catch {
      names = null;
    }
    displayNamesCache.set(uiLang, names);
  }
  return displayNamesCache.get(uiLang) ?? null;
}

export function getLocalizedLangName(code: string, englishName: string, uiLang: string): string {
  if (!code || !uiLang || uiLang.startsWith("en")) return englishName;
  const displayNames = getDisplayNames(uiLang);
  if (!displayNames) return englishName;
  const base = String(code).split("_")[0] ?? "";
  let name: string | undefined;
  try {
    name = displayNames.of(base);
  } catch {
    return englishName;
  }
  if (!name || name === base) return englishName;
  return name.charAt(0).toUpperCase() + name.slice(1);
}

export const isRtl = (lang: Lang) => rtlLangList.includes(lang ?? "");

export const getRtlDir = (lang: Lang): "rtl" | "ltr" => (isRtl(lang) ? "rtl" : "ltr");
